    // MARK: - Authenticated requests + 1001 retry-once

    func testAuthenticatedRequestRequiresSession() async {
        let subject = makeManager(transport: MockTransport(responses: []))
        do {
            _ = try await subject.authenticatedRequest("user.getStationList")
            XCTFail("expected notAuthenticated")
        } catch let error as SessionManagerError {
