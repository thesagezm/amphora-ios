//
//  SessionManagerTests.swift
//  PandoraCoreTests
//
//  Auth lifecycle against scripted responses: partner login → syncTime
//  offset → user login → store, and the 1001 retry-once contract.
//  All crypto fixtures generated from the vendored pithos Blowfish pipeline.
//
//  Swift 6 notes: actor-isolated properties/methods (isSubscriber,
//  hasSession, session, restore) are hoisted out of XCT* autoclosures —
//  `await` is not allowed inside an autoclosure.
//

import XCTest
@testable import PandoraCore

final class SessionManagerTests: XCTestCase {

    /// Fixed local clock for the whole scenario (2001-09-09). Static +
    /// @Sendable so `now:` closures need no captures of test-instance state.
    private static let clock: @Sendable () -> Date = {
        Date(timeIntervalSince1970: 1_000_000_000)
    }
    private static let localNow = Date(timeIntervalSince1970: 1_000_000_000)

    /// Encrypted syncTime fixtures (decryptKey), generated by running the
    /// vendored pithos blowfish.py + pandora_encrypt pipeline:
    ///
    /// - main: plaintext "PNDS1760000000PADPAD!!" → bytes[4..<14] =
    ///   "1760000000" → offset = 1760000000 − 1000000000 = 760000000
    /// - short: 8-byte plaintext → decrypts to 8 bytes < 14 → malformedSession
    /// - unparsable: bytes[4..<14] = "YYYYYYYYZZ" → Int parse fails →
    ///   malformedSession
    private static let syncTimeMain =
        "ac7b93e6a3c44c45258042bca01c9f6f40befffb546dee73"
    private static let syncTimeShort = "2d0462c4450f20b0"
    private static let syncTimeUnparsable =
        "9778de106b6d33770f0abd434a64bd037c500805a0da4edd"

    // MARK: - Fixture helpers

    /// ok envelope; `resultObjectJSON` must already be a JSON object.
    private func ok(_ resultObjectJSON: String) -> Result<Data, Error> {
        .success(Data("{\"stat\":\"ok\",\"result\":\(resultObjectJSON)}".utf8))
    }

    /// fail envelope with proper string escaping (JSONValue.encoded).
    private func fail(code: Int, message: String) -> Result<Data, Error> {
        .success(JSONValue.encoded([
            "stat": .string("fail"),
            "code": .int(code),
            "message": .string(message)
        ]))
    }

    private func partnerOK() -> Result<Data, Error> {
        ok(#"{"partnerId":"77","partnerAuthToken":"P-TOKEN","syncTime":"\#(Self.syncTimeMain)"}"#)
    }

    private func userOK(token: String = "U-TOKEN") -> Result<Data, Error> {
        ok(#"{"userId":"u-1","userAuthToken":"\#(token)","isSubscriber":true}"#)
    }

    private func makeManager(
        transport: MockTransport,
        store: (any SessionStore)? = nil
    ) -> SessionManager {
        SessionManager(
            client: LegacyPandoraClient(transport: transport),
            store: store,
            now: Self.clock
        )
    }

    private func cachedRecord(token: String = "U-EXPIRED") -> SessionRecord {
        SessionRecord(
            credentials: Credentials(username: "me@example.com", password: "hunter2"),
            tokens: SessionTokens(
                partnerId: "77",
                partnerAuthToken: "P-TOKEN",
                userId: "u-1",
                userAuthToken: token,
                timeOffset: 760_000_000
            ),
            isSubscriber: false
        )
    }

    // MARK: - Login

    func testLoginRunsPartnerThenUserAndStoresRecord() async throws {
        let transport = MockTransport(responses: [partnerOK(), userOK()])
        let store = InMemorySessionStore()
        let subject = makeManager(transport: transport, store: store)

        let tokens = try await subject.login(username: "me@example.com", password: "hunter2")

        XCTAssertEqual(tokens.partnerId, "77")
        XCTAssertEqual(tokens.userAuthToken, "U-TOKEN")
        XCTAssertEqual(tokens.timeOffset, 760_000_000)

        let isSubscriber = await subject.isSubscriber
        XCTAssertTrue(isSubscriber)
        let hasSession = await subject.hasSession
        XCTAssertTrue(hasSession)

        let saved = try XCTUnwrap(store.load())
        XCTAssertEqual(saved.credentials.username, "me@example.com")
        XCTAssertEqual(saved.tokens.userAuthToken, "U-TOKEN")
        XCTAssertTrue(saved.isSubscriber)

        // Request shape: partner login plain, user login encrypted + scoped.
        let requests = transport.requests
        XCTAssertEqual(requests.count, 2)

        let partnerReq = try XCTUnwrap(requests.first)
        XCTAssertEqual(partnerReq.contentType, "application/json")
        XCTAssertTrue(partnerReq.url.absoluteString.hasSuffix("?method=auth.partnerLogin"))
        XCTAssertEqual(
            String(decoding: partnerReq.body, as: UTF8.self),
            #"{"deviceModel":"android-generic","password":"AC7IBG09A3DTSYM4R41UJWL07VLN8JI7","username":"android","version":"5"}"#
        )

        let userReq = try XCTUnwrap(requests.last)
        XCTAssertEqual(userReq.contentType, "text/plain")
        XCTAssertEqual(
            userReq.url.absoluteString,
            "https://tuner.pandora.com/services/json/?partner_id=77&auth_token=P-TOKEN&method=auth.userLogin"
        )
        let userJSON = try PandoraCrypto.decryptFromHex(
            String(decoding: userReq.body, as: UTF8.self),
            key: PandoraAPI.encryptKey
        )
        let trimmed = userJSON.prefix { $0 != 0 }
        XCTAssertEqual(
            String(decoding: trimmed, as: UTF8.self),
            #"{"loginType":"user","partnerAuthToken":"P-TOKEN","password":"hunter2","returnIsSubscriber":true,"syncTime":1760000000,"username":"me@example.com"}"#
        )
    }

    func testLoginPropagatesCredentialRejection() async {
        let transport = MockTransport(responses: [
            partnerOK(),
            fail(code: 1002, message: "Invalid username or password")
        ])
        let subject = makeManager(transport: transport)

        var caught: PandoraAPIError?
        do {
            _ = try await subject.login(username: "me@example.com", password: "wrong")
            XCTFail("expected PandoraAPIError")
        } catch let error as PandoraAPIError {
            caught = error
        } catch {
            XCTFail("unexpected error type: \(error)")
        }
        XCTAssertTrue(caught?.isInvalidCredentials == true)
        let hasSession = await subject.hasSession
        XCTAssertFalse(hasSession, "failed login must leave no half-live session")
    }

    func testShortSyncTimeIsMalformedSession() async {
